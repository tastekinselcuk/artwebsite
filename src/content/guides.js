export function getGuideBySlug(slug) {
  return guides.find((g) => g.slug === slug) || null;
}

export function getGuideLocalized(guide, locale) {
  if (!guide) return null;
  const lang = locale === "en" ? "en" : "tr";
  return {
    slug: guide.slug,
    publishedAt: guide.publishedAt,
    image: guide.image,
    ...guide[lang],
  };
}

export function listGuides(locale) {
  return guides.map((g) => getGuideLocalized(g, locale));
}

/** Footer / öne çıkanlar — tüm listeyi şişirmemek için */
export function listFeaturedGuides(locale, limit = 3) {
  return listGuides(locale).slice(0, limit);
}

